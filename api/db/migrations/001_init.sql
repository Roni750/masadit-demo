-- Mock bookkeeping schema.
-- Documents use class table inheritance: shared columns live in `documents`,
-- each document type has its own table for type-specific columns, and
-- lines / payments / allocations reference `documents` with real foreign keys.

CREATE TYPE document_type AS ENUM (
  'quote',
  'order',
  'deal_invoice',
  'smart_invoice',
  'tax_invoice',
  'tax_invoice_receipt',
  'credit_invoice',
  'receipt',
  'delivery_note',
  'self_invoice'
);

CREATE TYPE payment_method AS ENUM ('bank_transfer', 'cash', 'check', 'credit_card', 'other');

CREATE TABLE clients (
  id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name            text NOT NULL,
  tax_id          text,
  payment_terms   text NOT NULL DEFAULT 'current',
  is_active       boolean NOT NULL DEFAULT true,
  phone           text,
  mobile          text,
  fax             text,
  email           text,
  delivery_email  text,
  contact_name    text,
  street          text,
  house_number    text,
  city            text,
  zip             text,
  po_box          text,
  country         text,
  balance_code    text,
  sort_code       text,
  opening_balance numeric(12, 2) NOT NULL DEFAULT 0,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE documents (
  id            bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type          document_type NOT NULL,
  -- Sequential per document type, shown to users as "#1001"; separate from id
  number        integer NOT NULL,
  client_id     bigint NOT NULL REFERENCES clients (id),
  branch_number integer NOT NULL DEFAULT 1,
  issued_at     date NOT NULL,
  currency      char(3) NOT NULL DEFAULT 'ILS',
  -- ILS per one unit of `currency`; 1 for ILS documents
  exchange_rate numeric(12, 6) NOT NULL DEFAULT 1 CHECK (exchange_rate > 0),
  -- Stored per document: the legal rate changes over time (17% in 2021, 18% in 2026)
  vat_rate      numeric(5, 2) NOT NULL CHECK (vat_rate >= 0),
  cancelled_at  timestamptz,
  deleted_at    timestamptz,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  UNIQUE (type, number),
  -- Target of the composite FKs below, which pin each subtype row to a document of the same type
  UNIQUE (id, type)
);

CREATE INDEX documents_client_idx ON documents (client_id);
CREATE INDEX documents_issued_at_idx ON documents (issued_at DESC, id DESC);

-- One table per document type. Each row extends exactly one `documents` row of that type.
CREATE TABLE quotes (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'quote' CHECK (type = 'quote'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE orders (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'order' CHECK (type = 'order'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE deal_invoices (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'deal_invoice' CHECK (type = 'deal_invoice'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE smart_invoices (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'smart_invoice' CHECK (type = 'smart_invoice'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE tax_invoices (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'tax_invoice' CHECK (type = 'tax_invoice'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE tax_invoice_receipts (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'tax_invoice_receipt' CHECK (type = 'tax_invoice_receipt'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE credit_invoices (
  id                   bigint PRIMARY KEY,
  type                 document_type NOT NULL DEFAULT 'credit_invoice' CHECK (type = 'credit_invoice'),
  -- The document this credit invoice credits ("credit for tax invoice #1000")
  credited_document_id bigint REFERENCES documents (id),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE receipts (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'receipt' CHECK (type = 'receipt'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE delivery_notes (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'delivery_note' CHECK (type = 'delivery_note'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE self_invoices (
  id   bigint PRIMARY KEY,
  type document_type NOT NULL DEFAULT 'self_invoice' CHECK (type = 'self_invoice'),
  FOREIGN KEY (id, type) REFERENCES documents (id, type) ON DELETE CASCADE
);

CREATE TABLE document_lines (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  position    integer NOT NULL,
  description text NOT NULL,
  quantity    numeric(12, 3) NOT NULL CHECK (quantity > 0),
  -- In the document's currency, before VAT
  unit_price  numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
  vat_exempt  boolean NOT NULL DEFAULT false,
  UNIQUE (document_id, position)
);

CREATE TABLE payments (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  document_id bigint NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  method      payment_method NOT NULL,
  paid_at     date NOT NULL,
  -- In ILS
  amount      numeric(12, 2) NOT NULL CHECK (amount > 0)
);

-- How documents get closed. A row with a closing document means "this document's amount
-- closes part of the target" (e.g. a credit invoice closing a tax invoice).
-- A row without one is a manual close.
CREATE TABLE allocations (
  id                  bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  target_document_id  bigint NOT NULL REFERENCES documents (id) ON DELETE CASCADE,
  closing_document_id bigint REFERENCES documents (id) ON DELETE CASCADE,
  -- In ILS
  amount              numeric(12, 2) NOT NULL CHECK (amount > 0),
  created_at          timestamptz NOT NULL DEFAULT now(),
  CHECK (closing_document_id IS NULL OR closing_document_id <> target_document_id)
);

CREATE INDEX allocations_target_idx ON allocations (target_document_id);
CREATE INDEX allocations_closing_idx ON allocations (closing_document_id);

-- Totals and status are derived, never stored, so they can't drift from lines and allocations.
CREATE VIEW document_summaries AS
WITH line_totals AS (
  SELECT
    d.id AS document_id,
    COALESCE(SUM(l.quantity * l.unit_price) FILTER (WHERE l.vat_exempt), 0) AS exempt_subtotal,
    COALESCE(SUM(l.quantity * l.unit_price) FILTER (WHERE NOT l.vat_exempt), 0) AS taxable_subtotal
  FROM documents d
  LEFT JOIN document_lines l ON l.document_id = d.id
  GROUP BY d.id
),
amounts AS (
  SELECT
    d.*,
    ROUND(t.exempt_subtotal, 2) AS exempt_subtotal,
    ROUND(t.taxable_subtotal, 2) AS taxable_subtotal,
    ROUND(t.taxable_subtotal * d.vat_rate / 100, 2) AS vat_amount
  FROM documents d
  JOIN line_totals t ON t.document_id = d.id
),
allocated AS (
  SELECT
    target_document_id AS document_id,
    SUM(amount) AS allocated_amount,
    bool_or(closing_document_id IS NULL) AS manually_closed
  FROM allocations
  GROUP BY target_document_id
)
SELECT
  a.id,
  a.type,
  a.number,
  a.client_id,
  a.branch_number,
  a.issued_at,
  a.currency,
  a.exchange_rate,
  a.vat_rate,
  a.cancelled_at,
  a.exempt_subtotal,
  a.taxable_subtotal,
  a.vat_amount,
  a.exempt_subtotal + a.taxable_subtotal + a.vat_amount AS total,
  ROUND((a.exempt_subtotal + a.taxable_subtotal + a.vat_amount) * a.exchange_rate, 2) AS total_ils,
  ROUND(a.vat_amount * a.exchange_rate, 2) AS vat_amount_ils,
  COALESCE(al.allocated_amount, 0) AS allocated_ils,
  GREATEST(ROUND((a.exempt_subtotal + a.taxable_subtotal + a.vat_amount) * a.exchange_rate, 2)
    - COALESCE(al.allocated_amount, 0), 0) AS open_balance_ils,
  CASE
    WHEN COALESCE(al.manually_closed, false) THEN 'closed'
    WHEN COALESCE(al.allocated_amount, 0) > 0
      AND al.allocated_amount >= ROUND((a.exempt_subtotal + a.taxable_subtotal + a.vat_amount) * a.exchange_rate, 2)
      THEN 'closed'
    ELSE 'open'
  END AS status
FROM amounts a
LEFT JOIN allocated al ON al.document_id = a.id
WHERE a.deleted_at IS NULL;
